// Write the Storybook Foundations pages (src/foundations/*.mdx) from
// src/tokens/tokens.index.json (made by buildTokens.mjs). The token data is written
// into the MDX as literal props, so Storybook's docs manifest (what AI agents read
// through the MCP server) carries every class, variable and value, not just pictures.
//
// Usage: node scripts/figma/buildTokenDocs.mjs
import fs from "node:fs";

const index = JSON.parse(fs.readFileSync("src/tokens/tokens.index.json", "utf8"));
const OUT = "src/foundations";
const MODES = index.modes;
const src = index.source;

const row = (t) => {
  const r = { figma: t.figma, classes: t.classes, cssVar: t.cssVar, value: t.value };
  if (t.aliasByMode) r.aliasByMode = t.aliasByMode;
  else if (t.alias) r.alias = t.alias;
  return r;
};
const pick = (fn) => index.tokens.filter(fn);
const json = (v) => JSON.stringify(v);
const table = (kind, rows, withModes) =>
  rows.length ? `<TokenTable kind="${kind}"${withModes ? ` modes={${json(MODES)}}` : ""} rows={${json(rows)}} />\n` : "_None._\n";

const head = (title, intro) => `{/* Generated by scripts/figma/buildTokenDocs.mjs from src/tokens/tokens.index.json. Do not edit by hand. */}
import { Meta } from "@storybook/addon-docs/blocks";
import { TokenTable, ColorRamps } from "./TokenBlocks";

<Meta title="Foundations/${title}" />

# ${title}

${intro}

Source: Figma file \`${src.figmaFileKey}\` (Graphene), read on ${src.exportedAt}. Use the
**Theme** switch in the toolbar to see the Dark values.

`;

const pages = {};
const semantic = (kind) => pick((t) => t.figma.startsWith(`+Theme/color/${kind}/`)).map(row);

// ---------- Colors ----------
const rampsOf = (collection, prefix) => {
  const groups = new Map();
  for (const t of pick((x) => x.collection === collection && x.type === "color")) {
    const parts = t.figma.split("/").slice(1);
    const name = parts.slice(0, -1).join("/") || parts[0];
    if (!groups.has(name)) groups.set(name, []);
    groups.get(name).push({ shade: parts.at(-1), className: t.classes[0] ?? "", cssVar: t.cssVar, hex: typeof t.value === "string" ? t.value : "" });
  }
  return [...groups].filter(([, s]) => s.length > 1).map(([name, shades]) => ({ name: `${prefix}${name}`, shades }));
};
pages.Colors =
  head(
    "Colors",
    `Use the **semantic** colours first: they carry the meaning and switch in Dark mode by
themselves. \`text-*\` for text, \`bg-*\` for surfaces, \`border-*\` for borders (also
\`ring-*\` and \`outline-*\`). Brand ramps (\`bg-brand-primary-500\`) and the raw palette
(\`bg-zinc-50\`) are for the rare case no semantic colour fits. Every colour takes an
opacity modifier: \`bg-primary-default/20\`.`,
  ) +
  `## Text\n\n${table("color", semantic("text"), true)}
## Background\n\n${table("color", semantic("background"), true)}
## Border\n\n${table("color", semantic("border"), true)}
## Other semantic colours\n\n${table(
    "color",
    pick((t) => t.type === "color" && ((t.figma.startsWith("+Theme/color/") && !/^\+Theme\/color\/(text|background|border)\//.test(t.figma)) || t.collection === "Annotation")).map(row),
    false,
  )}
## Brand ramps (.Brand)\n\n<ColorRamps ramps={${json(rampsOf(".Brand", "brand/"))}} />\n
## Primitive palette (Color)\n\n<ColorRamps ramps={${json(rampsOf("Color", ""))}} />\n`;

// ---------- Typography ----------
const tokenVal = (cssVar) => {
  const t = index.tokens.find((x) => `var(${x.cssVar})` === cssVar);
  if (!t) return cssVar;
  return typeof t.value === "object" ? t.value[MODES[0]] : t.value;
};
const textStyleRows = index.textStyles.map((s) => ({
  className: s.className,
  figma: s.className.replace(/^typo-/, ""),
  classes: [s.className],
  cssVar: "",
  value: `${tokenVal(s.fontSize)} / ${tokenVal(s.lineHeight)} · ${tokenVal(s.fontWeight)}${s.textTransform ? " · uppercase" : ""}`,
}));
pages.Typography =
  head(
    "Typography",
    `Prefer a **text style** class (\`typo-semi-bold-text-sm\`): it sets family, size, line
height and weight together, exactly like the Figma text style. Single utilities
(\`text-sm\`, \`font-semibold\`) are for small adjustments. Graphene's \`md\` size is
Tailwind's \`base\`; both class names work.`,
  ) +
  `## Text styles\n\n${table("text", textStyleRows, false)}
## Font size (with its line height)\n\n${table("space", pick((t) => t.figma.startsWith("Typography/font-size/")).map(row), false)}
## Line height\n\n${table("space", pick((t) => t.figma.startsWith("Typography/line-height/")).map(row), false)}
## Font weight\n\n${table("space", pick((t) => t.figma.startsWith("Typography/font-weight/")).map(row), false).replace('kind="space"', 'kind="opacity"')}
## Font family\n\n${table("space", pick((t) => /font-family/.test(t.figma)).map(row), false)}`;

// ---------- Spacing & sizing ----------
pages["Spacing and Sizing"] =
  head(
    "Spacing and Sizing",
    `The spacing scale feeds every spacing and size utility: \`p-4\`, \`m-4\`, \`gap-4\`,
\`w-4\`, \`h-4\` are all 16px. Use the **semantic** sizes for layout and components
(\`p-page-padding\`, \`gap-section-gap\`, \`h-component-md\`, \`w-modal-md\`) so pages
follow the design when it changes.`,
  ) +
  `## Page and section spacing (semantic)\n\n${table("space", pick((t) => /^\+Theme\/(tv )?page spacing\//.test(t.figma) && !t.classes.some((c) => c.startsWith("rounded"))).map(row), true)}
## Component, panel and icon sizes (semantic)\n\n${table("space", pick((t) => /^\+Theme\/(sizing|sticker size)\//.test(t.figma)).map(row), true)}
## Spacing scale\n\n${table("space", pick((t) => t.collection === "Spacing").map(row), false)}
## Breakpoints\n\n${table("space", pick((t) => t.collection === "Breakpoints").map(row), false)}`;

// ---------- Radius & borders ----------
pages["Radius and Borders"] =
  head(
    "Radius and Borders",
    `Use the semantic radius for components (\`rounded-default\`, \`rounded-button-md\`,
\`rounded-form-md\`, \`rounded-modal\`) and the scale (\`rounded-lg\`) only when nothing fits.`,
  ) +
  `## Radius (semantic)\n\n${table("radius", pick((t) => t.collection === "+Theme" && t.classes.some((c) => c.startsWith("rounded"))).map(row), true)}
## Radius scale\n\n${table("radius", pick((t) => t.figma.startsWith("Border/radius/")).map(row), false)}
## Border width\n\n${table("border", pick((t) => t.figma.startsWith("Border/width/") || t.figma === "+Theme/border/width/default").map(row), false)}`;

// ---------- Effects ----------
pages.Effects =
  head("Effects", "Shadows, blurs and opacity from the Figma effect styles and the Opacity collection.") +
  `## Shadows\n\n${table("shadow", index.effects.filter((e) => e.type === "shadow").map((e) => ({ figma: e.figma, classes: e.classes, cssVar: e.cssVar, value: e.css })), false)}
## Blur\n\n${table("space", index.effects.filter((e) => e.type === "blur").map((e) => ({ figma: e.figma, classes: e.classes, cssVar: e.cssVar, value: e.css })), false)}
## Opacity\n\n${table("opacity", pick((t) => t.collection === "Opacity").map(row), false)}`;

// ---------- Overview ----------
pages.Overview = `{/* Generated by scripts/figma/buildTokenDocs.mjs. Do not edit by hand. */}
import { Meta } from "@storybook/addon-docs/blocks";

<Meta title="Foundations/Overview" />

# Foundations

The design tokens come from Figma (**Graphene — Foundation**, file \`${src.figmaFileKey}\`,
read on ${src.exportedAt}). They are generated, never written by hand:

| File | What it is |
|---|---|
| \`src/tokens/design_token.json\` | All variables and styles, in the Tokens Brücke format (same as swt-fe) |
| \`src/tokens/tokens.css\` | CSS variables, always on; \`[data-theme="dark"]\` holds the Dark values |
| \`src/tokens/tailwind.tokens.js\` | The Tailwind theme pointing at those variables |
| \`src/tokens/tokens.index.json\` | Token → CSS variable → Tailwind class → value, for these pages |

## Rules

1. **Semantic first.** \`text-default\`, \`bg-surface\`, \`border-default\`, \`rounded-default\`,
   \`h-component-md\`, \`p-page-padding\`. They switch in Dark mode and follow design changes.
2. **Scale second.** \`p-4\`, \`rounded-lg\`, \`shadow-md\` when no semantic token fits.
3. **Raw palette last.** \`bg-zinc-100\`, \`bg-brand-primary-500\`: only for one-off cases.
4. **Never** hex values, \`style={{ color }}\`, or arbitrary values (\`p-[13px]\`).
5. **Text styles** as classes: \`typo-semi-bold-text-sm\` (see Typography).
6. **Dark mode** is \`<html data-theme="dark">\`; components need no \`dark:\` variants.

## Pages

| Page | Contents | Counts |
|---|---|---|
| Colors | Semantic text / background / border, brand ramps, palette | ${index.tokens.filter((t) => t.type === "color").length} colours |
| Typography | Text styles, sizes, line heights, weights, family | ${index.textStyles.length} text styles |
| Spacing and Sizing | Semantic page and component sizes, spacing scale, breakpoints | ${index.tokens.filter((t) => t.collection === "Spacing").length} steps |
| Radius and Borders | Semantic and scale radius, border widths | |
| Effects | Shadows, blurs, opacity | ${index.effects.length} effects |

## Update after a design change

\`\`\`bash
python3 scripts/figma/dumpServer.py 9232 <dir> &   # receiver for the plugin
# in Claude Code: figma_export_tokens + figma_execute(scripts/figma/plugin/readFoundation.js)
node scripts/figma/toBruecke.mjs <dir> src/tokens/design_token.json
node scripts/figma/buildTokens.mjs
node scripts/figma/buildTokenDocs.mjs
\`\`\`
`;

for (const [name, content] of Object.entries(pages)) {
  const file = `${OUT}/${name.replace(/ /g, "")}.mdx`;
  fs.writeFileSync(file, content);
  console.log(`Wrote ${file} (${Math.round(content.length / 1024)} KB)`);
}
