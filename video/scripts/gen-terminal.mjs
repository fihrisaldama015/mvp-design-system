// Turn the real terminal captures (docs/shield/video-assets/terminal/*.txt) into src/terminalText.ts,
// so the video renders them as text (sharp at any size) instead of scaled screenshots.
import fs from "node:fs";
import path from "node:path";
const dir = "../docs/shield/video-assets/terminal";
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".txt")).sort()) out[f.replace(/\.txt$/, "")] = fs.readFileSync(path.join(dir, f), "utf8").replace(/\n$/, "");
fs.writeFileSync("src/terminalText.ts", `// Generated by scripts/gen-terminal.mjs from docs/shield/video-assets/terminal. Do not edit.\nexport const T: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`);
console.log("terminalText.ts:", Object.keys(out).length, "captures");
